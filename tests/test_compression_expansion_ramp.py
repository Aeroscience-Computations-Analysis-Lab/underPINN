class TestCompressionExpansionRampGeometry:
    def setup_method(self):
        self.geom = CompressionExpansionRampGeometry(
            theta1_deg=10.0, theta2_deg=0.0, x1=0.4, x2=1.0, L=1.6, H=0.8)

    def test_wall_continuous_at_corners(self):
        """y_wall(x) must not jump at either corner -- both segments meet
        exactly, since a discontinuous wall would be an unphysical
        geometry (a gap or overlap in the solid boundary)."""
        eps = 1e-5
        y_left = self.geom.y_wall(np.array([self.geom.x1 - eps]))[0]
        y_right = self.geom.y_wall(np.array([self.geom.x1 + eps]))[0]
        assert y_left == pytest.approx(y_right, abs=1e-4)

        y_left2 = self.geom.y_wall(np.array([self.geom.x2 - eps]))[0]
        y_right2 = self.geom.y_wall(np.array([self.geom.x2 + eps]))[0]
        assert y_left2 == pytest.approx(y_right2, abs=1e-4)

    def test_wall_flat_before_first_corner(self):
        x = np.linspace(0.0, self.geom.x1, 10)
        y = self.geom.y_wall(x)
        assert np.allclose(y, 0.0)

    def test_wall_rises_between_corners(self):
        x = np.array([self.geom.x1, (self.geom.x1 + self.geom.x2) / 2, self.geom.x2])
        y = self.geom.y_wall(x)
        assert y[0] < y[1] < y[2]
        expected_y2 = (self.geom.x2 - self.geom.x1) * math.tan(math.radians(10.0))
        assert y[2] == pytest.approx(expected_y2, abs=1e-5)
        assert self.geom.y_corner2 == pytest.approx(expected_y2, abs=1e-5)

    def test_wall_flat_after_second_corner_when_theta2_zero(self):
        x = np.linspace(self.geom.x2, self.geom.L, 10)
        y = self.geom.y_wall(x)
        assert np.allclose(y, self.geom.y_corner2, atol=1e-5)

    def test_wall_normals_per_segment(self):
        # Flat segment (before x1): normal is (0, 1).
        nx, ny = self.geom.wall_normals(np.array([0.1]))
        assert nx[0] == pytest.approx(0.0, abs=1e-6)
        assert ny[0] == pytest.approx(1.0, abs=1e-6)

        # Compression incline (between x1 and x2): normal is
        # (-sin(theta1), cos(theta1)).
        nx, ny = self.geom.wall_normals(np.array([(self.geom.x1 + self.geom.x2) / 2]))
        assert nx[0] == pytest.approx(-math.sin(math.radians(10.0)), abs=1e-5)
        assert ny[0] == pytest.approx(math.cos(math.radians(10.0)), abs=1e-5)

        # Flat segment after x2 (theta2=0): normal is (0, 1) again.
        nx, ny = self.geom.wall_normals(np.array([self.geom.L - 0.1]))
        assert nx[0] == pytest.approx(0.0, abs=1e-6)
        assert ny[0] == pytest.approx(1.0, abs=1e-6)

    def test_interior_points_strictly_above_wall(self):
        pts = self.geom.sample_interior(500, seed=0)
        y_wall_at_x = self.geom.y_wall(pts[:, 0])
        assert np.all(pts[:, 1] > y_wall_at_x)
        assert np.all(pts[:, 0] >= 0.0) and np.all(pts[:, 0] <= self.geom.L)
        assert np.all(pts[:, 1] <= self.geom.H)

    def test_inlet_spans_full_height_at_x0(self):
        pts = self.geom.sample_inlet(20)
        assert np.allclose(pts[:, 0], 0.0)
        assert pts[:, 1].min() == pytest.approx(0.0, abs=1e-5)
        assert pts[:, 1].max() == pytest.approx(self.geom.H, abs=1e-5)

    def test_outlet_starts_above_wall_height_at_L(self):
        pts = self.geom.sample_outlet(20)
        assert np.allclose(pts[:, 0], self.geom.L)
        assert pts[:, 1].min() == pytest.approx(self.geom.y_corner2, abs=1e-5)
        assert pts[:, 1].max() == pytest.approx(self.geom.H, abs=1e-5)

    def test_upper_boundary_at_H(self):
        pts = self.geom.sample_upper(20)
        assert np.allclose(pts[:, 1], self.geom.H)

    def test_wall_segment_labels(self):
        seg = self.geom.wall_segment(np.array([0.1, 0.7, 1.3]))
        assert list(seg) == [0, 1, 2]

    def test_invalid_corner_ordering_raises(self):
        with pytest.raises(ValueError):
            CompressionExpansionRampGeometry(10.0, 0.0, x1=1.0, x2=0.4, L=1.6, H=0.8)
