GAMMA = 1.4
M_INF = 3.0
THETA1_DEG, THETA2_DEG = 10.0, 0.0     # compression by 10 deg, expansion back to 0
X1, X2, L, H = 0.4, 1.0, 1.6, 0.8
FIXED_AV = 1e-3                        # matches RampEvaluator's vetted value
N_INT, N_IN, N_W, N_UP = 30000, 300, 800, 200
BR, BI, BW, BU = 2048, 256, 400, 200
CORNER_N, CORNER_WIDTH = 0, 0.03  # opt-in EXTRA corner-focused wall points,
                                   # added on top of N_W's uniform coverage
N_W_TOTAL = N_W + CORNER_N        # actual wall-pool size; kept in sync with
                                   # N_W/CORNER_N by main() before any run_arm
W_PDE, W_INLET, W_WALL, W_UPPER = 1.0, 200.0, 80.0, 30.0
LAYERS = [2, 128, 128, 128, 128, 128, 4]
LR = 1e-3


def exact_states():
    """Freestream / post-shock / post-expansion primitive states, and the
    two reference-field dividing angles (shock line, average fan line) --
    all analytic, verified against textbook Prandtl-Meyer values and a
    full shock+expansion round trip (see module docstring)."""
    pde = CompressibleEulerPDE(model=None, gamma=GAMMA)
    rho1, u1, v1, p1 = pde.freestream(M_INF)

    shock = pde.oblique_shock(M_INF, THETA1_DEG)
    beta_rad = math.radians(shock["beta_deg"])

    exp_ = pde.prandtl_meyer_expansion(
        shock["M2"], shock["rho2"], shock["u2"], shock["v2"], shock["p2"],
        delta_deg=THETA1_DEG - THETA2_DEG)

    # Fan boundary angles (absolute, from horizontal), leading/trailing
    # Mach lines of the Prandtl-Meyer fan -- see module docstring for the
    # disclosed simplification (single averaged dividing line, not the
    # true continuum).
    mu_lead = math.asin(1.0 / shock["M2"])
    mu_trail = math.asin(1.0 / exp_["M2"])
    theta1_rad, theta2_rad = math.radians(THETA1_DEG), math.radians(THETA2_DEG)
    fan_lead_angle = theta1_rad + mu_lead
    fan_trail_angle = theta2_rad + mu_trail
    fan_avg_angle = 0.5 * (fan_lead_angle + fan_trail_angle)

    return {
        "freestream": (rho1, u1, v1, p1),
        "shock": shock, "beta_rad": beta_rad,
        "expansion": exp_, "fan_avg_angle": fan_avg_angle,
    }


def make_problem(seed: int):
    geom = CompressionExpansionRampGeometry(THETA1_DEG, THETA2_DEG, X1, X2, L, H)

    xy_r = jnp.array(geom.sample_interior(N_INT, seed=seed))
    xy_in = jnp.array(geom.sample_inlet(N_IN))
    xy_w = jnp.array(geom.sample_wall(N_W, n_corner=CORNER_N,
                                      corner_width=CORNER_WIDTH, seed=seed))
    assert xy_w.shape[0] == N_W_TOTAL, (
        f"wall pool size {xy_w.shape[0]} != N_W_TOTAL {N_W_TOTAL} -- "
        "N_W_TOTAL must be recomputed after any change to N_W/CORNER_N")
    xy_up = jnp.array(geom.sample_upper(N_UP))
    nx_w, ny_w = geom.wall_normals(np.array(xy_w[:, 0]))
    nx_w, ny_w = jnp.array(nx_w), jnp.array(ny_w)

    def domain_sampler(n, s):
        return geom.sample_interior(n, seed=s)

    return dict(geom=geom, xy_r=xy_r, xy_in=xy_in, xy_w=xy_w, xy_up=xy_up,
               nx_w=nx_w, ny_w=ny_w, domain_sampler=domain_sampler)


