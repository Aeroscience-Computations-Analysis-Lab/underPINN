"""A new 2-D **steady** benchmark case: compressible flow over a
compression-expansion ramp -- an oblique shock (compression) at the first
wall corner, then a Prandtl-Meyer expansion fan (expansion) at a second,
convex corner further downstream. Distinct from ``ablate_qr_deim.py``
(1-D *unsteady* Riemann problem) and from the existing single-corner
``RampEvaluator``/``RampGeometry`` (compression only, no expansion).

Physics: steady 2-D compressible Euler in conservative form
(``underPINN.pde.compressible_euler.CompressibleEulerPDE``, unchanged --
the residual doesn't depend on geometry). New pieces added to support this
case:

  * ``CompressibleEulerPDE.prandtl_meyer_expansion`` -- the Prandtl-Meyer
    exact-expansion-fan relation, verified against standard textbook
    values (nu(2)=26.38 deg, nu(3)=49.76 deg, nu_max(gamma=1.4)=130.45 deg)
    and against a full oblique-shock-then-expansion round trip: for
    M_inf=3, theta=10 deg, the post-shock-then-expansion state (M=2.973,
    p=0.716) comes back very close to but not identical to the M=3
    freestream (p=0.714) -- the small residual difference is the expected
    physical signature of entropy generated by the (irreversible) shock,
    which the (isentropic) expansion cannot undo. This match is itself a
    correctness check on the implementation, not assumed.
  * ``underPINN.geometry.ramp.CompressionExpansionRampGeometry`` -- a
    three-segment wall (flat / compression incline / back to flat),
    reusing ``RampGeometry``'s sampling methods' structure but with a
    per-point wall normal (the slip condition needs a different normal on
    each of the three segments, unlike the single-corner case's one fixed
    normal).

Same collocation-strategy-ablation methodology as
``ablate_qr_deim.py``/``ablate_qr_deim_ramp_ns.py`` (reused directly):
fixed artificial viscosity throughout (only the resampling strategy
varies), five arms:

  none            uniform collocation, no adaptive resampling
  rad             RAR-D/RAD magnitude-weighted resampling, full pool
  qr_deim         QR-DEIM-R resampling, full pool
  rad_hybrid      RAD, 80% fixed (uniform) / 20% adaptive
  qr_deim_hybrid  QR-DEIM-R, 80% fixed (uniform) / 20% adaptive

**Physics loss tracked separately from the total loss at every epoch**
(``pde_hist`` alongside ``loss_hist``, mirroring ``RampEvaluator``'s own
convention), reported in the summary table and given its own plot panel
distinct from the total-loss curve.

**A disclosed simplification in the exact reference field, not hidden as
if it were rigorous:** the Prandtl-Meyer fan is a *continuum* -- Mach
number varies smoothly with angle across it -- but this script's exact
field, like ``RampEvaluator``'s shock line, treats each of the two wall
features as an infinitely thin boundary for scoring purposes: the shock
line at the exact oblique-shock angle beta, and the expansion "line" at
the *average* of the fan's leading- and trailing-Mach-line angles. This
misclassifies the thin genuine fan sliver near the second corner but is a
reasonable approximation for a domain-averaged relative-L2 metric, and is
stated here explicitly rather than presented as exact.

Run:
    python benchmarks/suite/ablations/ablate_qr_deim_ramp_ce.py --epochs 5000
"""
