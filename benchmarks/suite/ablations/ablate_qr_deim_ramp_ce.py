def run_arm(arm: str, epochs: int, seed: int, prob, states,
           trainable_av: bool = False, av_lr: float = 1e-2,
           lbfgs_steps: int = 0, gradient_av: bool = False,
           av_sensor_k: float = 10.0, av_sensor_field: str = "rho",
           network: str = "mlp", n_fourier: int = 32,
           fourier_sigma: float = 10.0, optimizer: str = "adam",
           soap_b1: float = 0.95, soap_b2: float = 0.95,
           soap_precond_freq: int = 10) -> dict:
    strategy, adaptive_frac = ARM_CONFIG[arm]
    rho_inf, u_inf, v_inf, p_inf = states["freestream"]
    if trainable_av and optimizer == "soap":
        raise NotImplementedError(
            "trainable_av + optimizer='soap' not wired together -- "
            "trainable_av forces the optax.multi_transform net/av split, "
            "which doesn't currently offer SOAP as the 'net' sub-optimizer.")

    # network="fourier_mlp": trainable random-Fourier-feature embedding
    # [sin(Bx), cos(Bx)] prepended to the MLP (Tancik et al. 2020; Wang et
    # al. 2021's PINN-specific "eigenvector bias" analysis) -- directly
    # targets spectral bias, the well-documented tendency of a plain tanh
    # MLP to fit low-frequency content far faster than the high-frequency
    # content a sharp shock/expansion-fan transition needs. fourier_sigma
    # sets the initial frequency scale (larger -> higher-frequency bias);
    # B is itself trainable, so this is a *prior*, not a hard constraint.
    # network="gated_mlp": Wang et al. 2022's "Modified MLP" -- two input
    # encoders U/V (computed once from the raw input) are gate-blended into
    # every hidden layer, so each layer can recover lost input information
    # at any depth. This is architecture-level preconditioning: it directly
    # targets the pathological gradient-flow/conditioning problem in deep
    # tanh PINNs, distinct from both FourierMLP (input spectral basis) and
    # SOAP (optimizer curvature) already tried on this problem.
    if network == "fourier_mlp":
        model = FourierMLP(layers=LAYERS, n_fourier=n_fourier, sigma=fourier_sigma)
    elif network == "gated_mlp":
        model = GatedMLP(layers=LAYERS)
    else:
        model = MLP(layers=LAYERS)
    # gradient_av: per-point shock-sensor AV (eps(x,y)=art_visc*tanh(k*|grad
    # field|)) instead of one constant eps everywhere -- see
    # CompressibleEulerPDE's docstring. Mutually exclusive with
    # trainable_av (the combined-pytree learned-AV path); not combined here.
    pde = CompressibleEulerPDE(model, gamma=GAMMA, art_visc=FIXED_AV,
                               gradient_av=gradient_av, av_sensor_k=av_sensor_k,
                               av_sensor_field=av_sensor_field)
    net_params = model.init(jax.random.PRNGKey(seed), jnp.ones((1, 2)))
    sched = optax.cosine_decay_schedule(LR, epochs, alpha=1e-2)

    if trainable_av:
        # Genuinely separate optimizer for the AV scalar, not the network's
        # Adam+cosine-decay applied to a bigger combined pytree. Requested
        # directly: a single global scalar sharing the network's LR
        # *schedule* means its step size decays in lockstep with the
        # network's, on a timescale tuned for ~100k+ weights, not one
        # number -- it can get "clipped" into an early, possibly
        # suboptimal value well before the network itself has converged.
        # optax.multi_transform (the standard optax mechanism for
        # per-parameter-group optimizers) gives "net" and "log_av" their
        # own independent optimizer instances and state here: the network
        # keeps the existing Adam+cosine-decay recipe unchanged; log_av
        # gets its own Adam with a larger, *non*-decaying learning rate
        # (av_lr, default 1e-2 -- 10x the network's base LR, matching that
        # a single scalar can tolerate a larger step, and deliberately not
        # cosine-decayed so it can keep adapting for the full run rather
        # than freezing early alongside the network's schedule).
        log_av0 = CompressibleEulerPDE.inverse_softplus(FIXED_AV)
        params = {"net": net_params, "log_av": jnp.array(log_av0, dtype="f4")}

        net_opt = optax.chain(optax.scale_by_adam(),
                              optax.scale_by_schedule(sched), optax.scale(-1.0))
        av_opt = optax.chain(optax.scale_by_adam(), optax.scale(-av_lr))
        opt = optax.multi_transform(
            {"net": net_opt, "av": av_opt},
            param_labels={"net": "net", "log_av": "av"})
    elif optimizer == "soap":
        # SOAP (Vyas et al. 2024, arXiv:2409.11321): "Shampoo with Adam in
        # the Preconditioner's eigenbasis" -- maintains a Kronecker-
        # factored per-tensor curvature estimate (GG, the L/R matrices in
        # the paper), periodically (every soap_precond_freq steps)
        # eigendecomposes it to get a rotation Q, projects gradients into
        # that eigenbasis, runs ordinary Adam moment tracking there, then
        # projects the update back. A genuinely curvature-aware
        # (preconditioned) optimizer that's actually tractable at this
        # network's scale (unlike exact Gauss-Newton, O(n_params^3) and
        # already established as infeasible here) since it only ever
        # factors per-tensor dimensions (e.g. 128x128 for this network's
        # hidden layers), not the full parameter count. Uses the unofficial
        # JAX port github.com/haydn-jones/SOAP_JAX (source reviewed before
        # use) rather than a from-scratch reimplementation of a fairly
        # intricate algorithm. Same LR schedule as the Adam arm, so this
        # isolates "does the SOAP update rule help" as the only variable.
        params = net_params
        opt = soap(learning_rate=sched, b1=soap_b1, b2=soap_b2,
                  precondition_frequency=soap_precond_freq)
    else:
        params = net_params
        opt = optax.chain(optax.scale_by_adam(), optax.scale_by_schedule(sched),
                          optax.scale(-1.0))
    state = opt.init(params)

    xy_w, nx_w, ny_w = prob["xy_w"], prob["nx_w"], prob["ny_w"]

    @jax.jit
    def step(params, state, r_b, in_b, w_b, nxw_b, nyw_b, up_b):
        def loss_fn(p):
            res = pde.residual(p, r_b)
            pde_l = jnp.mean(jnp.sum(res ** 2, axis=-1))

            pv_in = pde.apply(p, in_b)
            in_l = (jnp.mean((pv_in[:, 0] - rho_inf) ** 2)
                   + jnp.mean((pv_in[:, 1] - u_inf) ** 2)
                   + jnp.mean((pv_in[:, 2] - v_inf) ** 2)
                   + jnp.mean((pv_in[:, 3] - p_inf) ** 2))

            pv_w = pde.apply(p, w_b)                # slip: u.n = 0, per-point normal
            wall_l = jnp.mean((pv_w[:, 1] * nxw_b + pv_w[:, 2] * nyw_b) ** 2)

            pv_up = pde.apply(p, up_b)                # freestream farfield
            up_l = (jnp.mean((pv_up[:, 0] - rho_inf) ** 2)
                   + jnp.mean((pv_up[:, 1] - u_inf) ** 2)
                   + jnp.mean((pv_up[:, 2] - v_inf) ** 2)
                   + jnp.mean((pv_up[:, 3] - p_inf) ** 2))

            total = W_PDE * pde_l + W_INLET * in_l + W_WALL * wall_l + W_UPPER * up_l
            return total, pde_l
        (total, pl), grads = jax.value_and_grad(loss_fn, has_aux=True)(params)
        updates, state = opt.update(grads, state)
        return optax.apply_updates(params, updates), state, total, pl

    key = jax.random.PRNGKey(seed + 7)
    xy_r = prob["xy_r"]
    xy_r_init = np.array(xy_r)
    resample_period = max(1, epochs // 5)

    n_adapt = max(1, round(adaptive_frac * N_INT)) if strategy is not None else 0
    n_fixed = N_INT - n_adapt
    xy_r_fixed = xy_r[:n_fixed] if n_fixed > 0 else None

    loss_hist: list = []
    pde_hist: list = []
    av_hist: list = []

    def train():
        nonlocal xy_r
        p, s, key_ = params, state, key
        total, pl = None, None
        for ep in range(epochs):
            if strategy is not None and ep > 0 and ep % resample_period == 0:
                if strategy == "rad":
                    new_pts = rad_resample(
                        pde, p, prob["domain_sampler"],
                        n_keep=n_adapt, n_candidates=5 * n_adapt,
                        k=1.0, c=1.0, seed=seed + ep)
                else:
                    new_pts = qr_deim_resample(
                        pde, p, prob["domain_sampler"],
                        n_keep=n_adapt, n_candidates=5 * n_adapt,
                        seed=seed + ep)
                adapt_pts = jnp.array(new_pts)
                xy_r = (jnp.concatenate([xy_r_fixed, adapt_pts], axis=0)
                       if xy_r_fixed is not None else adapt_pts)
            key_, k1, k2, k3, k4 = jax.random.split(key_, 5)
            ir = jax.random.randint(k1, (BR,), 0, N_INT)
            ii = jax.random.randint(k2, (BI,), 0, N_IN)
            iw = jax.random.randint(k3, (BW,), 0, N_W_TOTAL)
            iu = jax.random.randint(k4, (BU,), 0, N_UP)
            p, s, total, pl = step(p, s, xy_r[ir], prob["xy_in"][ii],
                                   xy_w[iw], nx_w[iw], ny_w[iw],
                                   prob["xy_up"][iu])
            loss_hist.append(float(total))
            pde_hist.append(float(pl))
            if trainable_av:
                av_hist.append(float(jax.nn.softplus(p["log_av"])))
        total.block_until_ready()
        return p, float(total), float(pl)

    (final_params, final_loss, final_pde_loss), wall = timed(train)

    # ------------------------------------------------------------------
    # Optional post-Adam second-order refinement: L-BFGS, not exact
    # Gauss-Newton -- underPINN/training/natural_gradient.py's Gauss-Newton
    # forms an explicit (n_params, n_params) matrix and does a dense solve
    # each step, O(n_params^3); it is documented there as tractable only for
    # "low hundreds to a few thousand" parameters (validated on a
    # 481-parameter network) and explicitly "not intended to replace
    # underPINN's Adam-based solvers on the large 3-D / compressible-flow
    # benchmarks" -- this network (LAYERS=[2,128,...,128,4]) has ~67,000
    # parameters, about 140x that, where forming the matrix alone would
    # need ~18GB and the solve would be computationally infeasible per
    # step. optax.lbfgs is the standard, genuinely scalable substitute
    # (limited-memory quasi-Newton, O(n_params * memory_size) storage, no
    # explicit Hessian/Jacobian ever formed) -- the same "Adam for coarse
    # convergence, L-BFGS for high-precision refinement" two-stage recipe
    # used throughout the PINN literature.
    #
    # L-BFGS's quasi-Newton history and line search assume a deterministic
    # objective, unlike Adam's per-step fresh random minibatch -- so this
    # phase uses one FIXED large batch (the full final interior pool,
    # post-resampling, plus the full inlet/wall/upper point sets), not a
    # re-randomized one each call.
    # ------------------------------------------------------------------
    lbfgs_hist: list = []
    lbfgs_pde_hist: list = []
    lbfgs_wall = 0.0
    if lbfgs_steps > 0:
        def full_loss_fn(p):
            res = pde.residual(p, xy_r)
            pde_l = jnp.mean(jnp.sum(res ** 2, axis=-1))
            pv_in = pde.apply(p, prob["xy_in"])
            in_l = (jnp.mean((pv_in[:, 0] - rho_inf) ** 2)
                   + jnp.mean((pv_in[:, 1] - u_inf) ** 2)
                   + jnp.mean((pv_in[:, 2] - v_inf) ** 2)
                   + jnp.mean((pv_in[:, 3] - p_inf) ** 2))
            pv_w = pde.apply(p, xy_w)
            wall_l = jnp.mean((pv_w[:, 1] * nx_w + pv_w[:, 2] * ny_w) ** 2)
            pv_up = pde.apply(p, prob["xy_up"])
            up_l = (jnp.mean((pv_up[:, 0] - rho_inf) ** 2)
                   + jnp.mean((pv_up[:, 1] - u_inf) ** 2)
                   + jnp.mean((pv_up[:, 2] - v_inf) ** 2)
                   + jnp.mean((pv_up[:, 3] - p_inf) ** 2))
            return W_PDE * pde_l + W_INLET * in_l + W_WALL * wall_l + W_UPPER * up_l

        def full_pde_loss(p):
            return jnp.mean(jnp.sum(pde.residual(p, xy_r) ** 2, axis=-1))

        lbfgs_opt = optax.lbfgs()
        lbfgs_value_and_grad = optax.value_and_grad_from_state(full_loss_fn)

        @jax.jit
        def lbfgs_step(p, s):
            value, grad = lbfgs_value_and_grad(p, state=s)
            updates, s = lbfgs_opt.update(grad, s, p, value=value, grad=grad,
                                          value_fn=full_loss_fn)
            p = optax.apply_updates(p, updates)
            return p, s, value

        jit_pde_loss = jax.jit(full_pde_loss)

        def lbfgs_train():
            p, s = final_params, lbfgs_opt.init(final_params)
            value = None
            for _ in range(lbfgs_steps):
                p, s, value = lbfgs_step(p, s)
                lbfgs_hist.append(float(value))
                lbfgs_pde_hist.append(float(jit_pde_loss(p)))
            return p, float(value)

        (final_params, final_loss), lbfgs_wall = timed(lbfgs_train)
        final_pde_loss = lbfgs_pde_hist[-1] if lbfgs_pde_hist else final_pde_loss

    geom = prob["geom"]
    XX, YY, mask = geom.make_grid(Nx=240, Ny=160)
    pts = jnp.array(np.stack([XX.ravel(), YY.ravel()], axis=1), "f4")
    pv = np.array(pde.apply(final_params, pts))
    a = np.sqrt(GAMMA * np.maximum(pv[:, 3], 1e-9) / np.maximum(pv[:, 0], 1e-9))
    mach_pred = (np.sqrt(pv[:, 1] ** 2 + pv[:, 2] ** 2) / np.maximum(a, 1e-9)).reshape(XX.shape)

    # ------------------------------------------------------------------
    # Primary scoring metric: SURFACE (wall) pressure, not the interior
    # Mach contour. The interior Mach field's exact reference needed the
    # disclosed simplification of collapsing the Prandtl-Meyer fan's
    # genuine angular width to a single averaged dividing line -- a real
    # approximation, correctly flagged as such (see the module docstring's
    # earlier version). The wall pressure does NOT need that
    # approximation: in Prandtl-Meyer theory, the expansion fan is
    # *centered exactly at the corner point*, so the flow immediately
    # adjacent to the wall jumps directly from one uniform state to the
    # next right at each corner -- the piecewise-constant reference is
    # exact on the wall specifically, even though the same assumption is
    # only approximate for the 2-D interior field away from the wall. The
    # Mach contour above is kept as a qualitative, PINN-only plot (no
    # "exact" claim attached to it anymore); this wall-pressure comparison
    # is the number now reported and scored.
    # ------------------------------------------------------------------
    Nx_wall = 400
    x_wall = np.linspace(0.0, L, Nx_wall, dtype="f4")
    y_wall = geom.y_wall(x_wall)
    xy_wall_eval = jnp.array(np.stack([x_wall, y_wall], axis=1), "f4")
    p_wall_pinn = np.array(pde.apply(final_params, xy_wall_eval))[:, 3]
    p_wall_exact = _exact_wall_pressure(x_wall, states)
    rel_l2_p_wall = float(relative_l2_error(
        jnp.array(p_wall_pinn), jnp.array(p_wall_exact)))

    eps_final = (float(jax.nn.softplus(final_params["log_av"]))
                if trainable_av else FIXED_AV)

    return {"strategy": arm, "base_method": strategy,
            "adaptive_frac": adaptive_frac, "n_fixed": n_fixed,
            "n_adapt": n_adapt, "epochs": epochs, "wall_s": wall,
            "ms_per_epoch": 1e3 * wall / epochs,
            "lbfgs_steps": lbfgs_steps, "lbfgs_wall_s": lbfgs_wall,
            "_lbfgs_hist": np.array(lbfgs_hist, "f4") if lbfgs_steps else None,
            "_lbfgs_pde_hist": np.array(lbfgs_pde_hist, "f4") if lbfgs_steps else None,
            "final_loss": final_loss, "final_pde_loss": final_pde_loss,
            "rel_l2": rel_l2_p_wall, "rel_l2_p_wall": rel_l2_p_wall,
            "trainable_av": trainable_av,
            "eps_final": eps_final,
            "_av_hist": np.array(av_hist, "f4") if trainable_av else None,
            "_xy_init": xy_r_init, "_xy_final": np.array(xy_r),
            "_XX": XX, "_YY": YY, "_mask": mask, "_mach_pred": mach_pred,
            "_x_wall": x_wall, "_p_wall_pinn": p_wall_pinn,
            "_p_wall_exact": p_wall_exact,
            "_loss_hist": np.array(loss_hist, "f4"),
            "_pde_hist": np.array(pde_hist, "f4")}


def _exact_wall_pressure(x_wall, states):
    """Exact (not approximate) surface pressure along the wall: freestream
    up to corner 1, the exact post-shock pressure between the two
    corners, the exact post-expansion pressure beyond corner 2. Unlike
    the interior Mach field, this needs no simplification -- see the
    rationale in run_arm just above where this is called."""
    p1 = states["freestream"][3]
    p_shock = states["shock"]["p2"]
    p_exp = states["expansion"]["p2"]
    p = np.full(x_wall.shape, p1, dtype=np.float32)
    p = np.where(x_wall >= X1, p_shock, p)
    p = np.where(x_wall >= X2, p_exp, p)
    return p


def plot_solutions(rows: dict, states, out_path: str) -> None:
    ok = {k: v for k, v in rows.items() if "error" not in v and "_mach_pred" in v}
    if not ok:
        return
    arms = [a for a in ARMS if a in ok]
    n = len(arms)
    ncols = max(n, 1)

    # Three rows: (0) PINN's own Mach contour, one panel per arm -- no
    # "exact" contour shown here any more, since that reference needed a
    # real simplification (collapsing the Prandtl-Meyer fan's genuine
    # angular width to one averaged line) that is only approximate in the
    # 2-D interior. (1) ONE shared surface-pressure panel, exact (which
    # *is* exact on the wall specifically, see _exact_wall_pressure's
    # docstring) plus every arm's PINN wall pressure overlaid -- this is
    # now the primary, unapproximated scoring comparison. (2) loss curves,
    # unchanged from before.
    fig, axes = plt.subplots(3, ncols, figsize=(4.6 * ncols, 11.5))
    if ncols == 1:
        axes = axes[:, None]
    XX, YY, mask = ok[arms[0]]["_XX"], ok[arms[0]]["_YY"], ok[arms[0]]["_mask"]
    vmin, vmax = 1.5, 3.2
    for col, arm in enumerate(arms):
        ax = axes[0, col]
        mp = np.ma.array(ok[arm]["_mach_pred"], mask=~mask)
        im = ax.pcolormesh(XX, YY, mp, cmap="turbo", vmin=vmin, vmax=vmax, shading="auto")
        ax.set_title(f"{arm} (PINN Mach)\nrel_L2(p_wall)={ok[arm]['rel_l2_p_wall']:.3f}",
                    fontsize=9)
        ax.set_aspect("equal")
        if col == n - 1:
            fig.colorbar(im, ax=ax, label="Mach")

    # Row 1: surface pressure, one shared panel (col 0), rest turned off --
    # same "exact + every arm overlaid on one axis" convention
    # ablate_qr_deim.py's plot_solutions already uses for its 1-D fields.
    ax_p = axes[1, 0]
    x_wall = ok[arms[0]]["_x_wall"]
    p_exact = ok[arms[0]]["_p_wall_exact"]
    ax_p.plot(x_wall, p_exact, "k-", lw=2, label="exact")
    for arm in arms:
        style = _ARM_STYLE.get(arm, {})
        ax_p.plot(ok[arm]["_x_wall"], ok[arm]["_p_wall_pinn"], lw=1.6,
                 label=f"{arm} (L2={ok[arm]['rel_l2_p_wall']:.3f})", **style)
    ax_p.axvline(X1, color="gray", lw=0.8, ls="--", alpha=0.6)
    ax_p.axvline(X2, color="gray", lw=0.8, ls="--", alpha=0.6)
    ax_p.set_xlabel("x (along wall)")
    ax_p.set_ylabel("surface pressure p")
    ax_p.set_title("Surface pressure: exact (piecewise, exact on the wall) "
                  "vs. every arm's PINN prediction", fontsize=10)
    ax_p.legend(fontsize=7, loc="best")
    ax_p.grid(alpha=0.3)
    for col in range(1, ncols):
        axes[1, col].axis("off")

    for col in range(ncols):
        ax = axes[2, col]
        if col < n:
            arm = arms[col]
            lh, ph = ok[arm].get("_loss_hist"), ok[arm].get("_pde_hist")
            if lh is not None and len(lh):
                ep = np.arange(1, len(lh) + 1)
                ax.plot(ep, lh, lw=1.2, label="total (Adam)", color="C0")
                ax.plot(ep, ph, lw=1.2, label="physics only (Adam)", color="C1")
                lbh = ok[arm].get("_lbfgs_hist")
                lbph = ok[arm].get("_lbfgs_pde_hist")
                if lbh is not None and len(lbh):
                    # Continue the x-axis right after Adam's last epoch, so
                    # the L-BFGS refinement phase reads as a continuation of
                    # the same training run, not a separate plot.
                    ep_lb = len(lh) + np.arange(1, len(lbh) + 1)
                    ax.plot(ep_lb, lbh, lw=1.6, ls="--",
                           label="total (L-BFGS)", color="C0")
                    ax.plot(ep_lb, lbph, lw=1.6, ls="--",
                           label="physics only (L-BFGS)", color="C1")
                    ax.axvline(len(lh), color="gray", lw=0.8, ls=":")
                ax.set_yscale("log")
                ax.set_xlabel("epoch (Adam), then L-BFGS step count appended")
                title = f"{arm}: loss"
                if ok[arm].get("eps_final") is not None and ok[arm].get("trainable_av"):
                    title += f"  (eps_final={ok[arm]['eps_final']:.2e})"
                ax.set_title(title, fontsize=9)
                ax.legend(fontsize=6, loc="upper right")
                ax.grid(alpha=0.3)
                av_h = ok[arm].get("_av_hist")
                if av_h is not None and len(av_h):
                    ax2 = ax.twinx()
                    ax2.plot(np.arange(1, len(av_h) + 1), av_h, lw=1.2,
                            color="green", label="AV (eps)")
                    ax2.set_ylabel("eps (AV coeff.)", color="green", fontsize=8)
                    ax2.tick_params(axis="y", labelcolor="green")
                    ax2.legend(fontsize=6, loc="lower right")
        else:
            ax.axis("off")

    fig.suptitle(f"Compression-expansion ramp (M={M_INF}, "
                f"theta1={THETA1_DEG} deg compression, "
                f"theta2={THETA2_DEG} deg expansion): PINN Mach field (top), "
                f"surface pressure exact-vs-PINN (middle), total vs. "
                f"physics-only loss (bottom)",
                fontsize=11, fontweight="bold")
    fig.tight_layout()
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"Solution + loss plot -> {out_path}")


def plot_migration(rows: dict, out_path: str) -> None:
    ok = {k: v for k, v in rows.items() if "error" not in v and "_xy_init" in v}
    if not ok:
        return
    arms = [a for a in ARMS if a in ok]
    fig, axes = plt.subplots(2, len(arms), figsize=(4.5 * len(arms), 7),
                             sharex=True, sharey=True)
    if len(arms) == 1:
        axes = axes[:, None]
    for col, arm in enumerate(arms):
        xy_init, xy_final = ok[arm]["_xy_init"], ok[arm]["_xy_final"]
        n_fixed = ok[arm].get("n_fixed", len(xy_init))
        for row, (xy, label) in enumerate([(xy_init, "initial"), (xy_final, "final")]):
            ax = axes[row, col]
            fixed, adapt = xy[:n_fixed], xy[n_fixed:]
            ax.scatter(fixed[:, 0], fixed[:, 1], s=1.2, alpha=0.12, c="#a0aec0")
            if len(adapt):
                ax.scatter(adapt[:, 0], adapt[:, 1], s=2.0, alpha=0.5, c="#c53030")
            ax.axvline(X1, color="k", ls="--", lw=0.8, alpha=0.5)
            ax.axvline(X2, color="k", ls="--", lw=0.8, alpha=0.5)
            ax.set_title(f"{arm} — {label}" if row == 0 else label, fontsize=9)
            if col == 0:
                ax.set_ylabel("y")
    fig.suptitle("Compression-expansion ramp: collocation pool, initial vs. "
                "final (dashed lines = the two wall corners)",
                fontsize=11, fontweight="bold")
    fig.tight_layout()
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"\nCollocation migration plot -> {out_path}")


def main() -> int:
    global FIXED_AV, N_INT, N_W, BR, BW, CORNER_N, CORNER_WIDTH, N_W_TOTAL
    ap = base_parser("Compression-expansion ramp (2-D steady Euler): "
                     "uniform vs. QR-DEIM-R vs. RAD collocation, fixed "
                     "artificial viscosity, physics loss tracked separately")
    ap.set_defaults(epochs=5000)
    ap.add_argument("--arms", nargs="*", default=list(ARMS), choices=list(ARMS))
    ap.add_argument("--art-visc", type=float, default=FIXED_AV,
                    help="fixed AV coefficient (ignored when --trainable-av; "
                         "used only as log_av's initial value in that case)")
    ap.add_argument("--trainable-av", action="store_true",
                    help="learn AV jointly with the network, via a "
                         "SEPARATE optax optimizer for the AV scalar "
                         "(optax.multi_transform) rather than the "
                         "network's own Adam+cosine-decay applied to a "
                         "combined pytree -- see run_arm's docstring "
                         "comment for the full rationale.")
    ap.add_argument("--av-lr", type=float, default=1e-2,
                    help="learning rate for the AV scalar's own optimizer "
                         "(only used with --trainable-av); not subject to "
                         "the network's cosine decay schedule")
    ap.add_argument("--lbfgs-steps", type=int, default=0,
                    help="if > 0, run this many L-BFGS refinement steps "
                         "(optax.lbfgs, with line search) after Adam "
                         "finishes, on one fixed full-size batch -- a "
                         "scalable second-order refinement stage; NOT "
                         "exact Gauss-Newton, which is documented as "
                         "intractable for a network this size (see "
                         "run_arm's docstring comment).")
    ap.add_argument("--n-int", type=int, default=N_INT,
                    help="interior collocation pool size (default: the "
                         "30,000-point config the none/rad/qr_deim 30k-"
                         "epoch comparison used)")
    ap.add_argument("--batch-r", type=int, default=BR,
                    help="interior per-step minibatch size")
    ap.add_argument("--n-w", type=int, default=N_W, help="wall point count")
    ap.add_argument("--batch-w", type=int, default=BW, help="wall batch size")
    ap.add_argument("--optimizer", type=str, default="adam",
                    choices=["adam", "soap"],
                    help="soap uses SOAP (Vyas et al. 2024) -- Shampoo-style "
                         "Kronecker-factored curvature preconditioning with "
                         "Adam run in the preconditioner's eigenbasis -- "
                         "instead of plain Adam, same LR schedule. Not "
                         "combined with --trainable-av.")
    ap.add_argument("--soap-b1", type=float, default=0.95,
                    help="SOAP's Adam-momentum beta1 (only used with "
                         "--optimizer soap)")
    ap.add_argument("--soap-b2", type=float, default=0.95,
                    help="SOAP's Adam-second-moment beta2 (only used with "
                         "--optimizer soap)")
    ap.add_argument("--soap-precond-freq", type=int, default=10,
                    help="steps between SOAP eigenbasis refreshes (only "
                         "used with --optimizer soap)")
    ap.add_argument("--network", type=str, default="mlp",
                    choices=["mlp", "fourier_mlp", "gated_mlp"],
                    help="fourier_mlp prepends a trainable random-Fourier-"
                         "feature embedding [sin(Bx), cos(Bx)] to the MLP "
                         "(Tancik et al. 2020 / Wang et al. 2021) -- a "
                         "direct fix for spectral bias, the documented "
                         "tendency of a plain tanh MLP to fit low-frequency "
                         "content far faster than a sharp shock/expansion-"
                         "fan transition needs. gated_mlp is Wang et al. "
                         "2022's Modified MLP -- gate-blended U/V input "
                         "encoders fused into every hidden layer, "
                         "architecture-level preconditioning against "
                         "pathological gradient flow.")
    ap.add_argument("--n-fourier", type=int, default=32,
                    help="number of Fourier frequency pairs (only used with "
                         "--network fourier_mlp)")
    ap.add_argument("--fourier-sigma", type=float, default=10.0,
                    help="initial Fourier frequency scale -- larger biases "
                         "toward higher frequencies; B is trainable so this "
                         "is a prior, not a hard constraint (only used with "
                         "--network fourier_mlp)")
    ap.add_argument("--gradient-av", action="store_true",
                    help="use a per-point shock-sensor artificial viscosity "
                         "eps(x,y) = art_visc * tanh(av_sensor_k * |grad "
                         "field|) instead of the constant art_visc "
                         "everywhere -- dissipation only activates near "
                         "steep gradients (shocks/expansion fans). Not "
                         "combined with --trainable-av.")
    ap.add_argument("--av-sensor-k", type=float, default=10.0,
                    help="steepness of the gradient_av tanh sensor (only "
                         "used with --gradient-av)")
    ap.add_argument("--av-sensor-field", type=str, default="rho",
                    choices=["rho", "u", "v", "p"],
                    help="which primitive field's gradient the gradient_av "
                         "sensor reads (only used with --gradient-av)")
    ap.add_argument("--corner-n", type=int, default=CORNER_N,
                    help="EXTRA wall points concentrated near the two wall "
                         "corners (x1, x2), ADDED ON TOP of the --n-w "
                         "uniform points (not reallocated from them -- an "
                         "earlier reallocating design starved the flat "
                         "plateau segments of coverage and measurably hurt "
                         "training). 0 (default) reproduces the original "
                         "uniform-only wall sampling exactly.")
    ap.add_argument("--corner-width", type=float, default=CORNER_WIDTH,
                    help="std of the Gaussian band of corner-focused wall "
                         "points around each corner (only used when "
                         "--corner-n > 0)")
    ap.add_argument("--tag", type=str, default="",
                    help="suffix for the results tag/plot filenames (e.g. "
                         "'_60k_large') -- REQUIRED whenever epochs/n-int/"
                         "arms differ from a previous run using the default "
                         "tag, since save_result/save_raw_arrays overwrite "
                         "results/ablation_qr_deim_ramp_ce.* unconditionally "
                         "and would silently destroy an earlier run's data "
                         "otherwise.")
    ap.add_argument("--replot", action="store_true")
    args = ap.parse_args()
    FIXED_AV = args.art_visc
    N_INT, BR, N_W, BW = args.n_int, args.batch_r, args.n_w, args.batch_w
    CORNER_N, CORNER_WIDTH = args.corner_n, args.corner_width
    N_W_TOTAL = N_W + CORNER_N
    tag = f"ablation_qr_deim_ramp_ce{args.tag}"
    plot_prefix = f"qr_deim_ramp_ce{args.tag}"

    states = exact_states()

    if args.replot:
        rows = load_raw_arrays(tag)
        saved = load_results(tag)[tag]
        for arm, scalars in saved["arms"].items():
            rows.setdefault(arm, {}).update(scalars)
        print(f"Replotting from saved results (epochs={saved['epochs']}, "
             f"seed={saved['seed']}, {len(rows)} arms) -- no training run.\n")
        plot_migration(rows, os.path.join(
            RESULTS_DIR, f"{plot_prefix}_collocation_migration.png"))
        plot_solutions(rows, states, os.path.join(
            RESULTS_DIR, f"{plot_prefix}_solutions.png"))
        return 0

    info = jax_device_info(require_gpu=not args.allow_cpu)
    warn_if_cpu(info)
    print(f"JAX backend: {info['platform']} ({info['device_name']})")
    print(f"Epochs per arm: {args.epochs}   seed: {args.seed}   "
         f"art_visc: {FIXED_AV}\n")
    print(f"Problem: compression-expansion ramp, M_inf={M_INF}, "
         f"theta1(compression)={THETA1_DEG} deg, theta2(expansion target)="
         f"{THETA2_DEG} deg, corners at x1={X1}, x2={X2}")
    print(f"  freestream M={M_INF:.3f}")
    print(f"  post-shock  M={states['shock']['M2']:.3f}  beta={states['shock']['beta_deg']:.2f} deg")
    print(f"  post-expansion M={states['expansion']['M2']:.3f}\n")

    prob = make_problem(args.seed)
    rows = {}
    for arm in args.arms:
        print(f"--- {arm}: {ARMS[arm]}")
        try:
            r = run_arm(arm, args.epochs, args.seed, prob, states,
                       trainable_av=args.trainable_av, av_lr=args.av_lr,
                       lbfgs_steps=args.lbfgs_steps, gradient_av=args.gradient_av,
                       av_sensor_k=args.av_sensor_k,
                       av_sensor_field=args.av_sensor_field,
                       network=args.network, n_fourier=args.n_fourier,
                       fourier_sigma=args.fourier_sigma,
                       optimizer=args.optimizer, soap_b1=args.soap_b1,
                       soap_b2=args.soap_b2,
                       soap_precond_freq=args.soap_precond_freq)
            rows[arm] = r
            av_note = f"  eps_final={r['eps_final']:.4e}" if args.trainable_av else ""
            lbfgs_note = (f"  lbfgs_wall={r['lbfgs_wall_s']:.1f}s"
                         if args.lbfgs_steps else "")
            print(f"    {r['ms_per_epoch']:6.2f} ms/ep  "
                 f"total_loss={r['final_loss']:.4e}  "
                 f"physics_loss={r['final_pde_loss']:.4e}{av_note}{lbfgs_note}  "
                 f"rel_L2(p_wall)={r['rel_l2_p_wall']:.4e}")
        except Exception as e:
            print(f"    FAILED: {type(e).__name__}: {e}")
            rows[arm] = {"error": f"{type(e).__name__}: {e}"}

    ok = {k: v for k, v in rows.items() if "error" not in v}
    if ok:
        base = ok.get("none", {}).get("rel_l2") or ok.get("rad", {}).get("rel_l2")
        print("\n" + "=" * 114)
        print(f"{'strategy':16s} {'ms/ep':>8s} {'total loss':>12s} "
             f"{'physics loss':>13s} {'rel L2(p_wall)':>14s} {'vs base':>9s} "
             f"{'eps_final':>10s}")
        print("-" * 114)
        for arm in ARMS:
            if arm not in ok:
                continue
            r = ok[arm]
            rel = f"{base / r['rel_l2']:.2f}x" if base else "-"
            eps_str = f"{r['eps_final']:.4e}" if args.trainable_av else "-"
            print(f"{arm:16s} {r['ms_per_epoch']:8.2f} {r['final_loss']:12.4e} "
                 f"{r['final_pde_loss']:13.4e} {r['rel_l2']:14.4e} {rel:>9s} "
                 f"{eps_str:>10s}")
        print("=" * 114)

    plot_migration(rows, os.path.join(
        RESULTS_DIR, f"{plot_prefix}_collocation_migration.png"))
    plot_solutions(rows, states, os.path.join(
        RESULTS_DIR, f"{plot_prefix}_solutions.png"))

    save_raw_arrays(tag, rows)
    rows_for_json = {k: {kk: vv for kk, vv in v.items() if not kk.startswith("_")}
                     for k, v in rows.items()}
    save_result(tag, {
        "problem": "compression_expansion_ramp", "epochs": args.epochs,
        "seed": args.seed, "device": info,
        "metric": "relative L2 of surface (wall) pressure vs. the exact "
                 "piecewise-constant reference (freestream / post-shock / "
                 "post-expansion) -- exact on the wall specifically, since "
                 "the Prandtl-Meyer fan is centered at the corner, unlike "
                 "the 2-D interior Mach field (kept as a qualitative, "
                 "PINN-only plot, no exact-field comparison claimed there "
                 "any more)",
        "physics_loss_note": "final_pde_loss / _pde_hist track the PDE-"
                             "residual term alone, separate from final_loss "
                             "(total, incl. inlet/wall/upper BC terms)",
        "art_visc": FIXED_AV, "trainable_av": args.trainable_av,
        "av_lr": args.av_lr, "lbfgs_steps": args.lbfgs_steps,
        "gradient_av": args.gradient_av, "av_sensor_k": args.av_sensor_k,
        "av_sensor_field": args.av_sensor_field,
        "network": args.network, "n_fourier": args.n_fourier,
        "fourier_sigma": args.fourier_sigma,
        "optimizer": args.optimizer, "soap_b1": args.soap_b1,
        "soap_b2": args.soap_b2, "soap_precond_freq": args.soap_precond_freq,
        "n_int": N_INT, "batch_r": BR,
        "n_w": N_W, "batch_w": BW,
        "corner_n": CORNER_N, "corner_width": CORNER_WIDTH,
        "n_w_total": N_W_TOTAL, "M_inf": M_INF,
        "theta1_deg": THETA1_DEG, "theta2_deg": THETA2_DEG,
        "x1": X1, "x2": X2, "L": L, "H": H,
        "exact_states": {k: v for k, v in states.items()
                        if k not in ("beta_rad", "fan_avg_angle")},
        "arms": rows_for_json,
    })
    return 0


